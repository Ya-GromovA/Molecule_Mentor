def get_questions_by_category(category: str) -> List[Dict[str, Any]]:
    """Возвращает вопросы указанной категории."""
    if category == "quick":
        # Быстрая викторина - случайные вопросы из всех категорий
        import random
        return random.sample(QUESTIONS, min(10, len(QUESTIONS)))
    elif category == "hardcore":
        # Сложный тест - только сложные вопросы
        hard = [q for q in QUESTIONS if q.get("difficulty", 1) >= 2]
        import random
        return random.sample(hard, min(20, len(hard)))
    else:
        return [q for q in QUESTIONS if q.get("category") == category]


def get_random_questions(count: int = 10, difficulty: int | None = None) -> List[Dict[str, Any]]:
    """Возвращает случайные вопросы."""
    import random
    pool = QUESTIONS
    if difficulty:
        pool = [q for q in QUESTIONS if q.get("difficulty", 1) == difficulty]
    return random.sample(pool, min(count, len(pool)))


